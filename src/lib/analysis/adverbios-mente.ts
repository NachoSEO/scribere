export function analyzeAdverbiosMente(
  context: AnalysisContext
): AnalysisIssue[] {
  const issues: AnalysisIssue[] = [];
  const regex = /(?<![a-záéíóúñüA-ZÁÉÍÓÚÑÜ])[a-záéíóúñüA-ZÁÉÍÓÚÑÜ]+mente(?![a-záéíóúñüA-ZÁÉÍÓÚÑÜ])/gi;
  let match: RegExpExecArray | null;

  while ((match = regex.exec(context.text)) !== null) {
    const word = match[0].toLowerCase();
    if (FALSE_POSITIVES.has(word)) continue;

    // Extra check: must end in -mente and have at least 2 chars before it
    if (word.length < 7) continue;

    issues.push({
      start: match.index,
      end: match.index + match[0].length,
      category: "adverbios-mente",
      message: `Adverbio en -mente: "${match[0]}". Considera reformular.`,
      severity: "info",
      match: match[0],
    });
  }

  return issues;
}
